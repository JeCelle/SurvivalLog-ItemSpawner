        // Custom Dragging and Input Tracking
        private bool isDragging = false;
        private Vector2 dragOffset;
        private bool clickStartedInMenu = false;
        private bool wasLeftClickHeld = false;

        // Absolute Rectangles for Custom Input
        private Rect rLoad, rSearch, rClear, rAmtM10, rAmtM1, rAmtP1, rAmtP10, rPrev, rNext;

        
        public override void OnUpdate()
        {
            if (Input.GetKeyDown(KeyCode.Insert) || Input.GetKeyDown(KeyCode.F8))
            {
                showMenu = !showMenu;
            }

            if (showMenu)
            {
                if (Cursor.lockState != CursorLockMode.None) Cursor.lockState = CursorLockMode.None;
                if (!Cursor.visible) Cursor.visible = true;
            }

            if (Input.GetKeyDown(KeyCode.F1))
            {
                DropItem(20002, 1);
            }

            // Custom Hardware Edge Triggers (Immune to ResetInputAxes interference)
            bool isLeftClickHeld = Input.GetMouseButton(0);
            bool isLeftClickDown = isLeftClickHeld && !wasLeftClickHeld;
            bool isLeftClickUp = !isLeftClickHeld && wasLeftClickHeld;
            wasLeftClickHeld = isLeftClickHeld;

            if (isLeftClickUp)
            {
                clickStartedInMenu = false;
                isDragging = false;
            }

            if (showMenu)
            {
                Vector2 mousePos = new Vector2(Input.mousePosition.x, Screen.height - Input.mousePosition.y);
                
                if (isLeftClickDown)
                {
                    if (windowRect.Contains(mousePos))
                    {
                        clickStartedInMenu = true;

                        Rect titleBar = new Rect(windowRect.x, windowRect.y, windowRect.width, 30);
                        if (titleBar.Contains(mousePos))
                        {
                            isDragging = true;
                            dragOffset = new Vector2(windowRect.x - mousePos.x, windowRect.y - mousePos.y);
                        }
                        else if (rLoad.Contains(mousePos)) { LoadItems(); currentPage = 0; }
                        else if (rSearch.Contains(mousePos)) { isTypingSearch = !isTypingSearch; }
                        else if (rClear.Contains(mousePos)) { searchText = ""; isTypingSearch = false; currentPage = 0; }
                        else if (rAmtM10.Contains(mousePos)) { amount = Math.Max(1, amount - 10); }
                        else if (rAmtM1.Contains(mousePos))  { amount = Math.Max(1, amount - 1); }
                        else if (rAmtP1.Contains(mousePos))  { amount += 1; }
                        else if (rAmtP10.Contains(mousePos)) { amount += 10; }
                        else if (rPrev.Contains(mousePos) && currentPage > 0) { currentPage--; }
                        else if (rNext.Contains(mousePos)) { currentPage++; }
                        else
                        {
                            foreach (var hit in dropHitboxes)
                            {
                                if (hit.rect.Contains(mousePos))
                                {
                                    DropItem(hit.itemID, amount);
                                    statusMessage = $"Dropped {amount}x [{hit.itemID}] successfully!";
                                    break;
                                }
                            }
                        }
                    }
                }

                if (isDragging)
                {
                    windowRect.x = mousePos.x + dragOffset.x;
                    windowRect.y = mousePos.y + dragOffset.y;
                }

                if (clickStartedInMenu)
                {
                    // Erase input for this frame so the game doesn't process it.
                    // Because clickStartedInMenu tracks edge states manually, this won't break the camera!
                    Input.ResetInputAxes();
                }
            }
        }

