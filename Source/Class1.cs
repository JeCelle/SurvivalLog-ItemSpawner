                rAmtP10 = new Rect(wx + 380, wy + 120, 40, 30);
                rPrev   = new Rect(wx + 180, wy + 160, 100, 30);
                rNext   = new Rect(wx + 290, wy + 160, 100, 30);

                // Draw the custom buttons using GUI.Box with text
                GUI.Box(rLoad, "Load Items from Game Memory");
                GUI.Label(new Rect(wx + 290, wy + 40, 350, 30), $"Status: {statusMessage}");

                // --- SEARCH ---
                GUI.Label(new Rect(wx + 20, wy + 80, 250, 30), "Search (Type to search):");
                string searchDisplay = string.IsNullOrEmpty(searchText) ? "(Click here and type...)" : searchText;
                if (isTypingSearch) searchDisplay += "|"; 
                GUI.Box(rSearch, searchDisplay);
                GUI.Box(rClear, "Clear");

                if (isTypingSearch && Event.current.type == EventType.KeyDown)
                {
                    if (Event.current.keyCode == KeyCode.Backspace)
                    {
                        if (searchText.Length > 0)
                        {
                            searchText = searchText.Substring(0, searchText.Length - 1);
                            currentPage = 0;
                        }
                    }
                    else if (Event.current.keyCode == KeyCode.Return || Event.current.keyCode == KeyCode.Escape)
                    {
                        isTypingSearch = false;
                    }
                    else
                    {
                        char c = Event.current.character;
                        if (c != 0 && !char.IsControl(c))
                        {
                            searchText += c;
                            currentPage = 0; 
                        }
                    }
                }

                // --- AMOUNT COUNTER ---
                GUI.Label(new Rect(wx + 20, wy + 120, 150, 30), "Amount to Drop:");
                GUI.Box(rAmtM10, "-10");
                GUI.Box(rAmtM1, "-1");
                GUI.Label(new Rect(wx + 280, wy + 120, 50, 30), amount.ToString());
                GUI.Box(rAmtP1, "+1");
                GUI.Box(rAmtP10, "+10");

                dropHitboxes.Clear();

                if (itemsLoaded)
                {
                    var filtered = allItems;
                    if (!string.IsNullOrEmpty(searchText))
                    {
                        string searchLower = searchText.ToLower();
                        filtered = allItems.Where(i => 
                            i.ID.ToString().Contains(searchLower) || 
                            i.LocalName.ToLower().Contains(searchLower) || 
                            (i.EnglishName != null && i.EnglishName.ToLower().Contains(searchLower))
                        ).ToList();
                    }

                    int totalPages = (int)Math.Ceiling((double)filtered.Count / itemsPerPage);
                    if (currentPage >= totalPages) currentPage = Math.Max(0, totalPages - 1);

                    // --- PAGINATION HEADER ---
                    GUI.Label(new Rect(wx + 20, wy + 160, 150, 30), $"Page {currentPage + 1} of {Math.Max(1, totalPages)}");
                    GUI.Box(rPrev, "<- Prev");
                    GUI.Box(rNext, "Next ->");

                    // --- ITEMS GRID ---
                    int startIndex = currentPage * itemsPerPage;
                    int endIndex = Math.Min(startIndex + itemsPerPage, filtered.Count);
                    int displayIndex = 0;

                    for (int i = startIndex; i < endIndex; i++)
                    {
                        var item = filtered[i];
                        int yPos = (int)wy + 210 + (displayIndex * 35);
                        
                        GUI.Label(new Rect(wx + 20, yPos, 500, 30), item.DisplayText);
                        
                        Rect rDrop = new Rect(wx + 530, yPos, 80, 30);
                        GUI.Box(rDrop, "Drop");
                        
                        // Register absolute hitbox for the event system
                        dropHitboxes.Add(new DropButtonHitbox { rect = rDrop, itemID = item.ID });
                        displayIndex++;
                    }
                }
            } 
            catch (Exception ex)
            {
                MelonLogger.Error($"[GUI Exception] {ex.Message}");
            }
        }

        private void LoadItems()
        {
            try
            {
                statusMessage = "Loading items from memory...";
                Type configManagerType = null;
                foreach (var asm in AppDomain.CurrentDomain.GetAssemblies())
                {
                    if (asm.GetName().Name.Contains("HotUpdate"))
                    {
                        configManagerType = asm.GetType("GameCore.HotUpdate.ConfigManager");
                        if (configManagerType == null)
                            configManagerType = asm.GetType("Il2CppGameCore.HotUpdate.ConfigManager");
                        if (configManagerType != null) break;
                    }
                }

                if (configManagerType == null) return;

                var instanceProp = configManagerType.GetProperty("Instance", BindingFlags.Public | BindingFlags.Static | BindingFlags.FlattenHierarchy);
                object instance = instanceProp?.GetValue(null);

                if (instance == null) return;

                var dictProp = configManagerType.GetProperty("_Config_Item_Dict", BindingFlags.Instance | BindingFlags.Public | BindingFlags.NonPublic);
                if (dictProp == null) return;

                object dictObj = dictProp.GetValue(instance);
                if (dictObj == null) return;

                allItems.Clear();
                var valuesProp = dictObj.GetType().GetProperty("Values");
                object valuesCol = valuesProp.GetValue(dictObj);
                var getEnumMethod = valuesCol.GetType().GetMethod("GetEnumerator");
                object enumerator = getEnumMethod.Invoke(valuesCol, null);

                var moveNextMethod = enumerator.GetType().GetMethod("MoveNext");
                var currentProp = enumerator.GetType().GetProperty("Current");

                while ((bool)moveNextMethod.Invoke(enumerator, null))
                {
                    object itemObj = currentProp.GetValue(enumerator);
                    if (itemObj == null) continue;

                    Type itemType = itemObj.GetType();
                    int id = (int)itemType.GetProperty("ID").GetValue(itemObj);
                    string name = (string)itemType.GetProperty("ItemName").GetValue(itemObj);
                    string localName = (string)itemType.GetProperty("ItemName_Local").GetValue(itemObj);

                    string englishTranslation = "UNKNOWN";
                    if (englishTranslations.ContainsKey(id)) { englishTranslation = englishTranslations[id]; }

                    string display = englishTranslation == "UNKNOWN" ? $"[{id}] {localName}" : $"[{id}] {englishTranslation} ({localName})";

                    allItems.Add(new ItemDef {
                        ID = id, Name = name ?? "", LocalName = localName ?? "",
                        EnglishName = englishTranslation == "UNKNOWN" ? null : englishTranslation,
                        DisplayText = display
                    });
                }

                allItems = allItems.OrderByDescending(i => i.EnglishName != null).ThenBy(i => i.ID).ToList();
                itemsLoaded = true;
                statusMessage = $"Loaded {allItems.Count} items.";
            }
            catch (Exception ex)
            {
                statusMessage = $"Error loading items: {ex.Message}";
            }
        }

        private void DropItem(int itemId, int dropAmt)
        {
            try
            {
                Type battleWorldType = null;
                foreach (var asm in AppDomain.CurrentDomain.GetAssemblies())
                {
                    if (asm.GetName().Name.Contains("HotUpdate"))
                    {
                        battleWorldType = asm.GetType("GameCore.HotUpdate.Battle.Logic.BattleLogicWorld");
                        if (battleWorldType == null)
                            battleWorldType = asm.GetType("Il2CppGameCore.HotUpdate.Battle.Logic.BattleLogicWorld");
                        if (battleWorldType != null) break;
                    }
                }

                if (battleWorldType == null) return;

                var instanceProp = battleWorldType.GetProperty("Instance", BindingFlags.Public | BindingFlags.Static | BindingFlags.FlattenHierarchy);
                object battleWorld = instanceProp?.GetValue(null);
                
                if (battleWorld == null) return;

                var dropManagerProp = battleWorldType.GetProperty("_DropItemManager", BindingFlags.NonPublic | BindingFlags.Instance | BindingFlags.Public);
                if (dropManagerProp != null)
                {
                    object dropManager = dropManagerProp.GetValue(battleWorld);
                    if (dropManager != null)
                    {
                        var dropMethod = dropManager.GetType().GetMethod("DropItem", new Type[] { typeof(int), typeof(int), typeof(int), typeof(int) });
                        if (dropMethod != null)
                        {
                            dropMethod.Invoke(dropManager, new object[] { itemId, dropAmt, 99999999, 0 });
                            return;
                        }
                    }
                }
            }
            catch { }
        }
    }
